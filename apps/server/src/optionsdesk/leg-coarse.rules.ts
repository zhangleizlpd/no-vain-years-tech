/**
 * 052 **粗排层**入口 (FR-004 / plan D-LAYER-1, ADR-0064 决策 1)。无 I/O、无 DI。
 *
 * 业界漏斗范式是「多个 candidate generator 各产子集 → **合并成单一候选池** → 统一打分」。
 * 本层就是那个合并槽位 —— 今天单路召回, 没有合并可做, 于是它是一个**恒等函数**。
 *
 * 🚨 **为什么现在就建一个什么都不做的函数**: 留出这个接缝的成本是一行 `return`, 不留的成本是
 * 将来多路召回落地时要把调用链拆开重接 (那时候召回、特征、精排三处都已长满断言)。ADR-0064
 * sunset #1「多路召回落地」是它由 no-op 转实体的触发条件。
 *
 * 🚫 **MUST NOT 在这里塞任何判据** (ADR-0064 决策 1 的禁令, plan Guardrail 5): 它一旦有逻辑就
 * 成了**第二个打分点** —— 与精排的口径必然分叉, 而分叉后两边都排得出顺序、都不会红。删腿更糟:
 * 候选池小一圈, 下游每一行的名次与特征值全变, **数字照样有、照样落 `[0,1]`**。
 * 机器判据 = `scripts/checks/check-optionsdesk-rule-constants.ts` 不变量 #6 (剥注释后扫本文件,
 * `if` / `filter` / `sort` / `>=` / `<=` 零命中)。
 *
 * 📌 **对元素类型无知是刻意的**: 合并去重是集合运算, 与「候选里装的是什么」无关。泛型让恒等性
 * 在类型层就成立 —— 出参与入参同一个 `T`, 想在这里改字段都改不了。
 *
 * 复杂度 `O(1)` (恒等; 转实体后为 `O(Σ 各路候选数)`)。
 */
export function coarseRank<T>(candidates: readonly T[]): readonly T[] {
  return candidates;
}
